        /** Functions in [category] (null: all; [COMMON] when [common]) whose name or description holds [query], with their signatures. */
        fun find(category: FunctionCategory?, common: Boolean, query: String, describe: (Int) -> String): List<FormulaFunctions.Signature> {
            val q = query.trim()
            val pool = when {
                common && q.isEmpty() -> COMMON.mapNotNull { FormulaFunctions.find(it) }
                category != null -> category.names.sorted().mapNotNull { FormulaFunctions.find(it) }
                else -> FormulaFunctions.all
            }
            if (q.isEmpty()) return pool
            val all = if (common) FormulaFunctions.all else pool
            val byName = all.filter { it.name.contains(q, ignoreCase = true) }.sortedBy { if (it.name.startsWith(q, ignoreCase = true)) 0 else 1 }
            val byText = all.filter { it !in byName && HELP[it.name]?.let { id -> describe(id).contains(q, ignoreCase = true) } == true }
            return byName + byText
        }
    }
